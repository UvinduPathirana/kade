import { bigint, customType, integer, pgTable, primaryKey, text, timestamp, uuid } from "drizzle-orm/pg-core";

const bytea = customType<{ data: Uint8Array; driverData: Buffer }>({
  dataType: () => "bytea",
  toDriver: (value) => Buffer.from(value.buffer, value.byteOffset, value.byteLength),
});

// ---------------------------------------------------------------------------------------------
// Platform tables: every service has these. Shapes are fixed by docs/backend/CONVENTIONS.md and by
// the Debezium outbox connector (debezium-connector.json); do not rename columns.
// ---------------------------------------------------------------------------------------------

export const outbox = pgTable("outbox", {
  id: uuid("id").primaryKey(), // event id, also used for consumer deduplication
  aggregatetype: text("aggregatetype").notNull(), // 'note' -> topic kade.note.events
  aggregateid: text("aggregateid").notNull(), // Kafka key
  type: text("type").notNull(), // fully-qualified proto message name
  payload: bytea("payload").notNull(), // protobuf-encoded event
  traceparent: text("traceparent"), // W3C trace context, copied into a Kafka header
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
});

export const processedEvents = pgTable("processed_events", {
  eventId: uuid("event_id").primaryKey(),
  handledAt: timestamp("handled_at", { withTimezone: true }).notNull().defaultNow(),
});

export const idempotencyKeys = pgTable(
  "idempotency_keys",
  {
    // e.g. "CreateNote:<user id>" so two callers can never collide on the same key.
    scope: text("scope").notNull(),
    key: text("key").notNull(),
    requestHash: text("request_hash").notNull(),
    response: bytea("response"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.scope, t.key] })],
);

// ---------------------------------------------------------------------------------------------
// Service tables: replace with your own aggregate(s).
// ---------------------------------------------------------------------------------------------

export const notes = pgTable("notes", {
  id: uuid("id").primaryKey(), // UUIDv7, generated by the service
  text: text("text").notNull(),
  amountMinor: bigint("amount_minor", { mode: "number" }).notNull(), // Money: int64 minor units
  currency: text("currency").notNull().default("LKR"),
  createdBy: text("created_by"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull(),
});

// Read model built by the kade.note.events consumer: the CQRS-projection shape that search builds
// from catalog events. applied_count exists to make exactly-once visible: replaying an event must
// leave it at 1 (processed_events dedup); a real projection would not need it.
export const noteProjections = pgTable("note_projections", {
  noteId: uuid("note_id").primaryKey(),
  text: text("text").notNull(),
  amountMinor: bigint("amount_minor", { mode: "number" }).notNull(),
  appliedCount: integer("applied_count").notNull().default(1),
  projectedAt: timestamp("projected_at", { withTimezone: true }).notNull().defaultNow(),
});

export const schema = { outbox, processedEvents, idempotencyKeys, notes, noteProjections };
