-- Example domain tables. Replace with your service's own.

CREATE TABLE notes (
  id           uuid        PRIMARY KEY,                     -- UUIDv7, generated by the service
  text         text        NOT NULL,
  amount_minor bigint      NOT NULL,                        -- money: minor units, never numeric/float
  currency     text        NOT NULL CHECK (currency ~ '^[A-Z]{3}$'),
  created_by   text        NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now()
);

-- Running totals maintained by the NoteCreated consumer. Shows optimistic locking: the same
-- read-check-write shape as a promotion budget or a ledger balance.
CREATE TABLE note_totals (
  currency     text        PRIMARY KEY CHECK (currency ~ '^[A-Z]{3}$'),
  total_minor  bigint      NOT NULL DEFAULT 0,
  note_count   bigint      NOT NULL DEFAULT 0,
  version      bigint      NOT NULL DEFAULT 0,              -- bumped on every update; UPDATE ... WHERE version = ?
  updated_at   timestamptz NOT NULL DEFAULT now()
);
